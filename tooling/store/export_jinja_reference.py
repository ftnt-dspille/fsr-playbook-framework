"""Generate docs/JINJA_FILTERS.md from the reference DB -- never edit the doc by hand.

    make jinja-docs
    PYTHONPATH=. .venv/bin/python -m tooling.store.export_jinja_reference [--check]

Sources, all in fsr_reference.db:
  * jinja_macros / jinja_globals / jinja_tests -- what the box registers, with
    the real ``inspect.signature()`` (``make jinja-export`` + probe_jinja_backend).
  * jinja_filter_probes -- the live evidence: every case rendered on a
    FortiSOAR, with input type, output type, preview or error
    (``make jinja-probe``).

Per filter the page states what was PROVEN: the input types that rendered, the
ones that raised, and the output type(s) observed -- each backed by a case row
that ``make jinja-verify`` can replay. Nothing in it is inferred.

``--check`` exits non-zero when the committed doc differs from what the DB
generates (the freshness test runs this).
"""
from __future__ import annotations

import argparse
import sqlite3
import sys
from collections import defaultdict
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
DOC = REPO_ROOT / "docs" / "JINJA_FILTERS.md"
_INPUT_ORDER = ["str", "int", "float", "bool", "list", "dict", "NoneType"]
# Opaque digests teach nothing beyond the type and can randomly contain a
# denylisted substring; show the type, not the value.
_DIGEST_FILTERS = {"password_hash", "hash", "hash_salt", "checksum"}


def _has_filter_rows(db: Path) -> bool:
    if not db.exists():
        return False
    try:
        conn = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
        return conn.execute("SELECT COUNT(*) FROM jinja_macros").fetchone()[0] > 0
    except sqlite3.OperationalError:
        return False  # bare/schema-only DB (e.g. a fresh data/ DB in CI)
    finally:
        try:
            conn.close()
        except Exception:
            pass


def _db_path() -> Path:
    # Prefer the freshly-probed full DB, but only if it actually carries the
    # jinja tables; otherwise the shipped slim catalog, which always does.
    full = REPO_ROOT / "data" / "fsr_reference.db"
    slim = REPO_ROOT / "fsr_playbooks" / "_data" / "fsr_reference.db"
    return full if _has_filter_rows(full) else slim


def _sig(name: str, signature: str | None) -> str:
    return f"`{name}{signature}`" if signature else f"`{name}` (signature not exported)"


def _first_line(doc: str | None) -> str:
    for line in (doc or "").strip().splitlines():
        line = line.strip()
        if line:
            return line.replace("|", "\\|")
    return ""


def _code(s: str | None, limit: int = 80) -> str:
    s = (s or "").replace("\n", "\\n").replace("|", "\\|").replace("`", "'")
    return f"`{s[:limit]}{'...' if len(s) > limit else ''}`" if s else ""


def build(conn: sqlite3.Connection) -> str:
    conn.row_factory = sqlite3.Row
    filters = conn.execute(
        "SELECT name, signature, module, description FROM jinja_macros ORDER BY lower(name)").fetchall()
    probes: dict[str, list[sqlite3.Row]] = defaultdict(list)
    for r in conn.execute("SELECT * FROM jinja_filter_probes ORDER BY filter_name, case_id"):
        probes[r["filter_name"]].append(r)
    builds = sorted({r["fsr_build"] for rows in probes.values() for r in rows})
    globals_ = conn.execute("SELECT name, signature, module, description FROM jinja_globals ORDER BY name").fetchall()
    tests = conn.execute("SELECT name, signature, module, description FROM jinja_tests ORDER BY name").fetchall()

    n_cases = sum(len(v) for v in probes.values())
    n_ok = sum(r["ok"] for v in probes.values() for r in v)
    out: list[str] = [
        "# FortiSOAR Jinja filter reference",
        "",
        "<!-- GENERATED by tooling/store/export_jinja_reference.py from fsr_reference.db. Do not edit. -->",
        "",
        "Every filter, global and test registered in the FortiSOAR playbook engine, with what each filter",
        "was **proven** to accept and return by rendering it on a live box through",
        "`/api/wf/api/jinja-editor/` (the engine a running playbook uses).",
        "",
        f"- Evidence: {n_cases} rendered cases ({n_ok} rendered, {n_cases - n_ok} raised) "
        f"across {len(probes)} of {len(filters)} filters.",
        f"- Probed on: {', '.join(builds) or 'not yet probed'}.",
        "- \"Accepts\" lists input types that rendered with no arguments (or the curated case's arguments);",
        "  \"Raises on\" lists input types that errored. Output types are Python type names from `type_debug`.",
        "- `generator` output is lazy: pipe it through `| list` before indexing or storing it.",
        "",
        "## Refreshing this page",
        "",
        "```bash",
        "make jinja-export INSTANCE=<alias>   # dump filters/globals/tests + signatures from the box over SSH",
        "make jinja-probe  INSTANCE=<alias>   # render every probe case live, store the evidence",
        "make jinja-docs                      # regenerate this file",
        "make jinja-verify INSTANCE=<alias>   # replay every case; fails if a filter breaks or changes type",
        "```",
        "",
        "Add cases for filters with required arguments, or behaviour worth pinning, in",
        "`tooling/probes/jinja_filter_cases.yaml`.",
        "",
        "## Filters",
        "",
        "| Filter | Accepts (no args) | Raises on | Returns | Source |",
        "|---|---|---|---|---|",
    ]
    for f in filters:
        rows = probes.get(f["name"], [])
        matrix = [r for r in rows if r["case_id"].startswith("input:")]
        ok_in = [t for t in _INPUT_ORDER if any(r["input_type"] == t and r["ok"] for r in matrix)]
        bad_in = [t for t in _INPUT_ORDER if any(r["input_type"] == t and not r["ok"] for r in matrix)]
        outs = sorted({r["output_type"] for r in rows if r["ok"] and r["output_type"]})
        accepts = ", ".join(ok_in) if matrix else ("needs args" if rows else "not probed")
        out.append(f"| [`{f['name']}`](#{f['name'].lower()}) | {accepts} | {', '.join(bad_in)} "
                   f"| {', '.join(outs) or '-'} | {f['module'] or '-'} |")

    out += ["", "## Filter details", ""]
    for f in filters:
        rows = probes.get(f["name"], [])
        out += [f"### {f['name']}", "", _sig(f["name"], f["signature"]), ""]
        if f["description"]:
            out += [_first_line(f["description"]), ""]
        if not rows:
            out += ["_No live evidence yet: add a case to `jinja_filter_cases.yaml`._", ""]
            continue
        out += ["| Case | Input | Args | Result | Output |", "|---|---|---|---|---|"]
        for r in rows:
            args = r["template"].split(f"| {f['name']}(", 1)[1].rsplit(")) | type_debug", 1)[0] \
                if f"| {f['name']}(" in r["template"] else ""
            res = f"`{r['output_type']}`" if r["ok"] else "raises"
            if r["ok"] and f["name"] in _DIGEST_FILTERS:
                detail = "_(digest elided)_"
            elif r["ok"]:
                detail = _code(r["output_preview"])
            else:
                detail = _code(r["error"], 120)
            out.append(f"| {r['case_id']} | {_code(r['input_json'], 40)} | {_code(args, 40)} | {res} | {detail} |")
        out.append("")

    for title, rows in (("Globals", globals_), ("Tests", tests)):
        out += [f"## {title}", "", "| Name | Signature | Source | Summary |", "|---|---|---|---|"]
        for g in rows:
            out.append(f"| `{g['name']}` | {_code(g['signature'], 90)} | {g['module'] or '-'} "
                       f"| {_first_line(g['description'])[:120]} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if the committed doc is stale")
    ap.add_argument("--db", type=Path, default=None)
    args = ap.parse_args(argv)
    text = build(sqlite3.connect(args.db or _db_path()))
    if args.check:
        if not DOC.exists() or DOC.read_text() != text:
            print(f"{DOC} is stale: run `make jinja-docs`", file=sys.stderr)
            return 1
        return 0
    DOC.write_text(text)
    print(f"[jinja-docs] wrote {DOC} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
